// Each Code node gets only the lib.js declarations it uses (transitively), in lib order,
// which keeps the workflow small enough to push through the MCP.
const decls = [];
for (const chunk of lib.split(/\n(?=(?:function|const) )/)) {
  const m = chunk.match(/^(?:function|const) (\w+)/);
  if (m) decls.push({ name: m[1], text: chunk.replace(/\n+(\/\/[^\n]*\n?)*$/, '').replace(/\n\/\/ -{10,}[^\n]*$/, '') + '\n' });
}
const ident = /\b(pr[A-Z]\w*|PR_[A-Z_]+)\b/g;
function needed(src) {
  const want = new Set();
  const visit = s => { for (const [, id] of s.matchAll(ident)) if (!want.has(id)) { const d = decls.find(x => x.name === id); if (d) { want.add(id); visit(d.text.slice(d.text.indexOf(id) + id.length)); } } };
  visit(src);
  return decls.filter(d => want.has(d.name)).map(d => d.text).join('');
}
const code = f => {
  const body = read('nodes/' + f);
  return `// GENERATED by tools/prompt-review/build-workflow.mjs from lib.js + nodes/${f}. Do not edit in n8n.\n${consts}\n\n// ---- from lib.js\n${needed(body)}\n// ---- nodes/${f}\n${body}`;
};
